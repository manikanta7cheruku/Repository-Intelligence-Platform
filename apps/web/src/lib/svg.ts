export interface ExportMeta {
  title: string;
  repo: string;
  commit: string | null;
  date: string;
  tool: string;
  legend?: string[];
}

const esc = (s: string): string =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/** Wraps chart markup into a self-contained, light themed SVG document with a caption and metadata. */
export function buildExportSvg(
  inner: string,
  width: number,
  height: number,
  meta: ExportMeta,
): string {
  const head = 62;
  const legendRow = meta.legend && meta.legend.length > 0;
  const w = Math.max(Math.round(width) + 48, 560);
  const h = Math.round(height) + head + (legendRow ? 52 : 34);
  const legend = legendRow
    ? `<text class="c-text c-small c-muted" x="24" y="${h - 32}">${esc((meta.legend ?? []).join("   |   "))}</text>`
    : "";
  const commit = meta.commit ? `  |  commit ${esc(meta.commit.slice(0, 7))}` : "";
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" role="img" aria-label="${esc(meta.title)}"><style>${chartCss(EXPORT_PALETTE)}</style><rect width="100%" height="100%" fill="#FFFFFF"/><text class="c-text c-title" x="24" y="30">${esc(meta.title)}</text><text class="c-text c-small c-muted" x="24" y="48">${esc(meta.repo)}${commit}  |  ${esc(meta.date)}  |  ${esc(meta.tool)}</text><g transform="translate(24,${head})">${inner}</g>${legend}<text class="c-text c-small c-muted" x="24" y="${h - 12}">Generated by RIP. Static analysis, not a security audit.</text></svg>`;
}

export function download(name: string, data: BlobPart, type: string): void {
  const url = URL.createObjectURL(new Blob([data], { type }));
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  document.body.append(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

export async function svgToPngBlob(svg: string, scale = 2): Promise<Blob> {
  const m = /width="(\d+(?:\.\d+)?)" height="(\d+(?:\.\d+)?)"/.exec(svg);
  const w = Number(m?.[1] ?? 800);
  const h = Number(m?.[2] ?? 600);
  const url = URL.createObjectURL(new Blob([svg], { type: "image/svg+xml" }));
  try {
    const img = new Image();
    await new Promise<void>((res, rej) => {
      img.onload = () => res();
      img.onerror = () => rej(new Error("The image could not be rendered"));
      img.src = url;
    });
    const canvas = document.createElement("canvas");
    canvas.width = Math.round(w * scale);
    canvas.height = Math.round(h * scale);
    const ctx = canvas.getContext("2d");
    if (!ctx) throw new Error("Canvas is not available");
    ctx.fillStyle = "#FFFFFF";
    ctx.fillRect(0, 0, canvas.width, canvas.height);
    ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
    return await new Promise<Blob>((res, rej) =>
      canvas.toBlob((b) => (b ? res(b) : rej(new Error("PNG encoding failed"))), "image/png"),
    );
  } finally {
    URL.revokeObjectURL(url);
  }
}

/** PDF through the browser print dialog (Save as PDF). No library, nothing leaves the browser. */
export function printSvg(svg: string, title: string): void {
  const frame = document.createElement("iframe");
  frame.setAttribute("aria-hidden", "true");
  frame.style.cssText = "position:fixed;right:0;bottom:0;width:0;height:0;border:0";
  document.body.append(frame);
  const doc = frame.contentDocument;
  if (!doc) {
    frame.remove();
    return;
  }
  doc.open();
  doc.write(
    `<!doctype html><title>${esc(title)}</title><style>@page{margin:14mm}body{margin:0}svg{max-width:100%;height:auto}</style>${svg}`,
  );
  doc.close();
  setTimeout(() => {
    frame.contentWindow?.focus();
    frame.contentWindow?.print();
    setTimeout(() => frame.remove(), 1500);
  }, 200);
}

