import { DIMENSION_LABELS } from "../glossary/glossary.js";
import type { ExecutiveSummary, Report, ScoreRecord } from "../ir/types.js";

const LANG_NAMES: Record<string, string> = {
  typescript: "TypeScript",
  javascript: "JavaScript",
  python: "Python",
  go: "Go",
  rust: "Rust",
  java: "Java",
  csharp: "C#",
  cpp: "C++",
  c: "C",
  ruby: "Ruby",
  php: "PHP",
  kotlin: "Kotlin",
  swift: "Swift",
  shell: "Shell",
};
const name = (l: string): string => LANG_NAMES[l] ?? l.charAt(0).toUpperCase() + l.slice(1);
const plural = (n: number, one: string, many = `${one}s`): string =>
  `${n.toLocaleString("en-US")} ${n === 1 ? one : many}`;
const join = (xs: string[]): string =>
  xs.length <= 1 ? (xs[0] ?? "") : `${xs.slice(0, -1).join(", ")} and ${xs[xs.length - 1]}`;
const pct = (v: number): string => `${Math.round(v * 1000) / 10} percent`;

/** Deterministic summary written from report facts with fixed templates. Nothing here is generated by a model. */
export function buildExecutiveSummary(r: Report): ExecutiveSummary {
  const totalCode = r.scope.languages.reduce((s, l) => s + l.codeLines, 0);
  const main = r.scope.languages
    .filter((l) => totalCode > 0 && l.codeLines / totalCode >= 0.1)
    .map((l) => name(l.language));
  const frameworks = r.detection.frameworks
    .map((f) => f.name)
    .filter((f) => !["Vitest", "Jest", "pytest", "Mocha", "Playwright", "Cypress"].includes(f))
    .slice(0, 4);
  const modules = r.graph.modules.length;
  const headline =
    totalCode === 0
      ? `${r.repository.name} has no recognized source code in a supported language.`
      : `${r.repository.name} is a ${main.length > 0 ? join(main) : "multi-language"} repository with ${plural(totalCode, "line")} of code${modules > 0 ? ` in ${plural(modules, "module")}` : ""}${frameworks.length > 0 ? `, using ${join(frameworks)}` : ""}.`;

  const overview: string[] = [];
  overview.push(
    `The analysis processed ${r.repository.analyzedCodeFiles} of ${r.repository.codeFiles} code files (${r.repository.productionFiles} production, ${r.repository.testFiles} test) out of ${r.repository.totalFiles} files in total.${r.graph.resolution.ratio !== null ? ` ${pct(r.graph.resolution.ratio)} of internal imports were resolved, which is the main reliability number for the dependency graph.` : ""}`,
  );
  const fileCycles = r.graph.cycles.filter((c) => c.scope === "file" && !c.typeOnly).length;
  const modCycles = r.graph.cycles.filter((c) => c.scope === "module").length;
  if (r.graph.nodes.length > 0) {
    overview.push(
      fileCycles + modCycles === 0
        ? `The ${plural(r.graph.nodes.length, "production file")} form a dependency graph with ${plural(r.graph.edges.length, "edge")} and no circular dependencies.`
        : `The dependency graph has ${plural(fileCycles, "runtime file cycle")} and ${plural(modCycles, "module cycle")}.`,
    );
  } else
    overview.push(
      "No dependency graph could be built because no analyzed production source files were found, so architecture conclusions are not available.",
    );
  const assessed = r.scores.filter(
    (s): s is ScoreRecord & { value: number } => s.state === "assessed" && s.value !== null,
  );
  const notAssessed = r.scores.filter((s) => s.state === "not-assessed");
  if (assessed.length > 0)
    overview.push(
      `Scores: ${assessed.map((s) => `${DIMENSION_LABELS[s.dimension] ?? s.dimension} ${s.value} (${s.confidence} confidence)`).join(", ")}.`,
    );
  if (notAssessed.length > 0)
    overview.push(
      `Not assessed: ${notAssessed.map((s) => DIMENSION_LABELS[s.dimension] ?? s.dimension).join(", ")}. "Not assessed" means the inputs were missing, not that the value is zero.`,
    );
  if (r.history.available) {
    const h = r.history;
    overview.push(
      `History (${h.source === "github-api" ? "GitHub API sample" : "Git"}): ${plural(h.commitsAnalyzed ?? 0, "commit")} from ${plural(h.contributors.length, "contributor")}${h.pullRequests ? `, ${plural(h.pullRequests.merged, "merged pull request")} in the recent sample` : ""}${h.releases ? `, ${plural(h.releases.count, "release")}` : ""}.`,
    );
  }

  const strengths: string[] = [];
  if (r.graph.nodes.length >= 5 && fileCycles + modCycles === 0)
    strengths.push("No circular dependencies between files or modules.");
  if (
    r.graph.resolution.ratio !== null &&
    r.graph.resolution.ratio >= 0.98 &&
    r.graph.resolution.internalImports >= 10
  )
    strengths.push(
      `Almost all internal imports resolve (${pct(r.graph.resolution.ratio)}), so graph conclusions are well supported.`,
    );
  if (r.practices.ci.providers.length > 0)
    strengths.push(
      `Continuous integration is configured (${r.practices.ci.providers.join(", ")}).`,
    );
  if (r.practices.documentation.adrCount > 0)
    strengths.push(
      `${plural(r.practices.documentation.adrCount, "architecture decision record")} document design choices.`,
    );
  if (
    r.metrics.duplication.assessed &&
    r.metrics.duplication.ratio !== null &&
    r.metrics.duplication.ratio < 0.03
  )
    strengths.push(`Low code duplication (${pct(r.metrics.duplication.ratio)}).`);
  if (
    r.security.secrets.some((s) => s.assessed) &&
    !r.findings.some((f) => f.ruleId.startsWith("security.secret."))
  )
    strengths.push("No committed secrets were detected by the checks that ran.");
  if (r.testCoverage.ingested && r.testCoverage.lineRate !== null && r.testCoverage.lineRate >= 0.7)
    strengths.push(`Measured test coverage is ${pct(r.testCoverage.lineRate)}.`);
  if (r.detection.lockfiles.length > 0)
    strengths.push("A dependency lockfile pins exact versions.");

  const concerns: string[] = [];
  const osv = r.findings.filter((f) => f.ruleId === "security.osv");
  if (osv.length > 0) {
    const pkgs = new Set(
      osv.map((f) => (f.tags.find((t) => t.startsWith("package:")) ?? "").slice(8)).filter(Boolean),
    );
    const dev = osv.filter((f) => f.tags.includes("dev")).length;
    concerns.push(
      `${plural(osv.length, "known vulnerability", "known vulnerabilities")} affect ${plural(pkgs.size, "package")} (${osv.filter((f) => f.severity === "critical" || f.severity === "high").length} critical or high${dev > 0 ? `, ${dev} in development-only tools` : ""}). Reachability is not assessed.`,
    );
  }
  const wf = r.findings.filter((f) => f.ruleId.startsWith("security.workflow."));
  if (wf.length > 0)
    concerns.push(
      `${plural(wf.length, "risky GitHub Actions setting")} found, for example unpinned actions.`,
    );
  if (fileCycles + modCycles > 0)
    concerns.push(
      `${plural(fileCycles + modCycles, "circular dependency", "circular dependencies")} detected.`,
    );
  if (r.rules.evaluated && (r.rules.violations ?? 0) > 0)
    concerns.push(`${plural(r.rules.violations ?? 0, "architecture rule violation")}.`);
  const riskHigh = r.risk.files.filter((f) => f.risk >= 65);
  if (riskHigh.length > 0)
    concerns.push(
      `${plural(riskHigh.length, "file")} rank high on the risk index, the top one is ${riskHigh[0]?.path}.`,
    );
  const cx = r.metrics.complexityDistribution;
  if (cx && cx.high + cx.veryHigh > 0) {
    const n = cx.high + cx.veryHigh;
    concerns.push(
      `${plural(n, "function")} ${n === 1 ? "has" : "have"} high or very high complexity.`,
    );
  }
  if (r.practices.tests.testFiles === 0 && r.repository.productionFiles > 0)
    concerns.push("No test files were detected.");
  if (r.testCoverage.ingested && r.testCoverage.lineRate !== null && r.testCoverage.lineRate < 0.5)
    concerns.push(`Measured test coverage is only ${pct(r.testCoverage.lineRate)}.`);
  if (r.status !== "complete")
    concerns.push("The report is partial, so conclusions describe only the analyzed part.");
  const low = r.scope.languages
    .filter((l) => l.supportLevel === 1 && l.codeLines > 0)
    .map((l) => name(l.language));
  if (low.length > 0)
    concerns.push(
      `${join(low)} only received detection and line counts, so architecture conclusions do not cover it.`,
    );

  const nextSteps = r.recommendations.slice(0, 3).map((x) => x.title);
  return { headline, overview, strengths, concerns, nextSteps };
}
