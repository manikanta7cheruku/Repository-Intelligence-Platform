import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { openLocalWorkspace } from "../acquire/local.js";
import { resolveConfig } from "../config/config.js";
import { detectPractices } from "../practices/detect.js";
import { classifyPath, looksGenerated } from "./classify.js";
import { languageOf } from "./languages.js";
import { detectProject } from "./manifests.js";

let dirs: string[] = [];
afterEach(() => {
  for (const d of dirs) rmSync(d, { recursive: true, force: true });
  dirs = [];
});
const ws = (files: Record<string, string>) => {
  const d = mkdtempSync(join(tmpdir(), "rl-det-"));
  dirs.push(d);
  for (const [p, c] of Object.entries(files)) {
    mkdirSync(join(d, p, ".."), { recursive: true });
    writeFileSync(join(d, p), c);
  }
  return openLocalWorkspace(d, resolveConfig({}));
};

describe("classifyPath", () => {
  const kind = (p: string) => classifyPath(p).kind;
  it("classifies sources, tests, generated, vendored, docs, config and binaries with reasons", () => {
    expect(kind("src/a.ts")).toBe("source");
    expect(kind("src/a.test.ts")).toBe("test");
    expect(kind("tests/helper.py")).toBe("test");
    expect(kind("fixtures/x/src/a.ts")).toBe("test");
    expect(kind("packages/core/dist/index.js")).toBe("generated");
    expect(kind("types/index.d.ts")).toBe("generated");
    expect(kind("vendor/lib/a.js")).toBe("vendored");
    expect(kind("README.md")).toBe("docs");
    expect(kind("docs/guide.md")).toBe("docs");
    expect(kind("package.json")).toBe("config");
    expect(kind("logo.png")).toBe("binary");
    expect(kind("weird.xyz")).toBe("other");
    expect(classifyPath("src/a.ts").reason).toMatch(/typescript/);
  });
  it("maps extensions to languages", () => {
    expect(languageOf("a.tsx")).toBe("typescript");
    expect(languageOf("a.mjs")).toBe("javascript");
    expect(languageOf("a.py")).toBe("python");
    expect(languageOf("a.txt")).toBeNull();
  });
  it("detects generated headers", () => {
    expect(looksGenerated("// Code generated by protoc. DO NOT EDIT.\npackage x")).toBe(true);
    expect(looksGenerated("export const a = 1;")).toBe(false);
  });
});

describe("detectProject", () => {
  it("finds package managers, frameworks, entrypoints, runtimes and the license", () => {
    const w = ws({
      "package.json": JSON.stringify({
        name: "x",
        main: "src/index.ts",
        bin: { x: "bin/cli.js" },
        dependencies: { next: "1", react: "1" },
        devDependencies: { vitest: "1" },
      }),
      "pnpm-lock.yaml": "lockfileVersion: 9",
      "src/index.ts": "",
      "bin/cli.js": "",
      Dockerfile: "FROM node",
      LICENSE: "Apache License\nVersion 2.0, January 2004",
      "requirements.txt": "django==4.0\npytest\n",
      "manage.py": "",
    });
    const d = detectProject(w);
    expect(d.packageManagers).toEqual(["npm", "pip", "pnpm"]);
    expect(d.lockfiles).toEqual(["pnpm-lock.yaml"]);
    expect(d.frameworks.map((f) => f.name)).toEqual([
      "Django",
      "Next.js",
      "pytest",
      "React",
      "Vitest",
    ]);
    expect(d.entrypoints.map((e) => e.path)).toEqual(["bin/cli.js", "manage.py", "src/index.ts"]);
    expect(d.runtimes).toEqual(["node", "python"]);
    expect(d.license).toEqual({ file: "LICENSE", spdxGuess: "Apache-2.0" });
    expect(d.buildTools).toContain("docker");
  });
  it("tolerates broken manifests", () => {
    const d = detectProject(ws({ "package.json": "{ not json" }));
    expect(d.manifests).toEqual(["package.json"]);
    expect(d.frameworks).toEqual([]);
  });
});

describe("detectPractices", () => {
  it("detects CI, tests, linters, strict TypeScript, README sections and ADRs", () => {
    const w = ws({
      ".github/workflows/ci.yml": "name: x",
      "package.json": JSON.stringify({
        scripts: { test: "vitest" },
        devDependencies: { vitest: "1", eslint: "1", prettier: "1" },
      }),
      "tsconfig.json": '{ // comment\n "compilerOptions": { "strict": true } }',
      "src/a.ts": "",
      "src/a.test.ts": "",
      "README.md": "# Title\n\n## Installation\n\n## Usage\n\nwords",
      "CONTRIBUTING.md": "x",
      LICENSE: "MIT License",
      ".env.example": "",
      "docs/adr/0001-x.md": "x",
      "docs/adr/README.md": "x",
    });
    const files = [...w.files].map((f) => ({
      id: f.path,
      path: f.path,
      language: f.path.endsWith(".ts") ? "typescript" : null,
      kind: classifyPath(f.path).kind,
      kindReason: "",
      bytes: 0,
      lines: null,
      codeLines: null,
      analyzed: true,
      notAnalyzedReason: null,
    }));
    const p = detectPractices(w, files, detectProject(w));
    expect(p.ci.providers).toEqual(["GitHub Actions"]);
    expect(p.tests).toMatchObject({
      testFiles: 1,
      sourceFiles: 1,
      testToSourceFileRatio: 1,
      coverageReport: "not-ingested",
    });
    expect(p.tests.frameworks).toContain("Vitest");
    expect(p.quality).toMatchObject({
      linters: ["ESLint"],
      formatters: ["Prettier"],
      typeCheckers: ["TypeScript"],
      strictTypeScript: true,
    });
    expect(p.documentation.readme).toMatchObject({
      path: "README.md",
      hasInstall: true,
      hasUsage: true,
    });
    expect(p.documentation.files).toMatchObject({
      contributing: true,
      license: true,
      codeOfConduct: false,
    });
    expect(p.documentation.adrCount).toBe(1);
    expect(p.setup.envExample).toBe(true);
  });
  it("reports null, not zero, for ratios when there are no source files", () => {
    const w = ws({ "README.md": "# x" });
    const p = detectPractices(w, [], detectProject(w));
    expect(p.tests.testToSourceFileRatio).toBeNull();
    expect(p.quality.strictTypeScript).toBeNull();
  });
});
