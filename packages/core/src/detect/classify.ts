import type { FileKind } from "../ir/types.js";
import { GlobSet } from "../util/glob.js";
import { basename, extname } from "../util/paths.js";
import { isBinaryExt, isDataExt, languageOf } from "./languages.js";

export interface Classification {
  kind: FileKind;
  reason: string;
  language: string | null;
}

const VENDORED = new GlobSet([
  "vendor/**",
  "third_party/**",
  "third-party/**",
  "**/vendor/**",
  "**/vendored/**",
  "bower_components/**",
]);
const GENERATED_PATH = new GlobSet([
  "**/dist/**",
  "**/build/**",
  "**/out/**",
  "**/coverage/**",
  "**/.next/**",
  "**/__generated__/**",
  "**/generated/**",
  "*.min.js",
  "*.min.css",
  "*.bundle.js",
  "*.d.ts",
  "*.map",
  "*_pb2.py",
  "*.pb.go",
  "*.g.dart",
]);
/** Test data, not code of the project: sample repositories, snapshots and recorded inputs. */
const FIXTURE_PATH = new GlobSet([
  "**/fixtures/**",
  "**/__fixtures__/**",
  "**/testdata/**",
  "**/test-data/**",
  "**/test_data/**",
]);
const TEST_PATH = new GlobSet([
  "**/__tests__/**",
  "**/tests/**",
  "**/test/**",
  "**/spec/**",
  "**/e2e/**",
  "**/__mocks__/**",
  "*.test.*",
  "*.spec.*",
  "*_test.go",
  "*_test.py",
  "test_*.py",
  "conftest.py",
]);
const CONFIG_NAMES = new Set([
  "package.json",
  "tsconfig.json",
  "jsconfig.json",
  "pyproject.toml",
  "setup.py",
  "setup.cfg",
  "requirements.txt",
  "go.mod",
  "Cargo.toml",
  "pom.xml",
  "build.gradle",
  "Makefile",
  "Dockerfile",
  "docker-compose.yml",
  ".gitignore",
  ".editorconfig",
  ".eslintrc",
  ".prettierrc",
  "biome.json",
  "vite.config.ts",
  "next.config.js",
  "jest.config.js",
  "vitest.config.ts",
  "tox.ini",
  ".nvmrc",
  "pnpm-workspace.yaml",
]);
const DOC_NAMES =
  /^(readme|contributing|changelog|license|licence|code_of_conduct|security|authors|notice)(\.(md|markdown|txt|rst|adoc))?$/i;
const GENERATED_HEADER = /@generated|DO NOT EDIT|Code generated by|auto-?generated/i;

/** Classifies a file using path rules first. Reasons are recorded so every decision is inspectable. */
export function classifyPath(path: string): Classification {
  const language = languageOf(path);
  const name = basename(path);
  if (isBinaryExt(path))
    return { kind: "binary", reason: `binary extension ${extname(path)}`, language: null };
  if (VENDORED.matches(path))
    return { kind: "vendored", reason: "path under a vendor directory", language };
  if (GENERATED_PATH.matches(path))
    return {
      kind: "generated",
      reason: "path matches a generated or build output pattern",
      language,
    };
  if (FIXTURE_PATH.matches(path))
    return {
      kind: "fixture",
      reason: "test data directory (fixtures or testdata), not analyzed as project code",
      language,
    };
  if (TEST_PATH.matches(path))
    return { kind: "test", reason: "path matches a test pattern", language };
  if (
    DOC_NAMES.test(name) ||
    path.startsWith("docs/") ||
    extname(path) === ".md" ||
    extname(path) === ".rst"
  ) {
    return { kind: "docs", reason: "documentation file or directory", language: null };
  }
  if (language) return { kind: "source", reason: `${language} source extension`, language };
  if (CONFIG_NAMES.has(name) || isDataExt(path) || name.startsWith(".")) {
    return { kind: "config", reason: "configuration or data file", language: null };
  }
  return { kind: "other", reason: "no matching rule", language: null };
}

/** Content check run on the first part of a source file to demote generated code. */
export function looksGenerated(head: string): boolean {
  return GENERATED_HEADER.test(head.slice(0, 400));
}
